#!/usr/bin/env python3
"""The Rust side of tinymind (C++)'s examples/onnx_digits_int8: its three
generated models, from the ONNX models that example commits, and its
reference data.

  python3 -I tools/import_onnx/example_digits.py [OUT_DIR]

writes, into OUT_DIR (default examples/common):

  onnx_digits_model.rs       models/digits_int8.onnx, int8 (as model.hpp)
  onnx_digits_int4_model.rs  models/digits_qat_int8.onnx with int4_dense and
                             int4_conv (as model_int4.hpp)
  onnx_digits_16x8_model.rs  models/digits_int8.onnx with activation_bits=16
                             (as model_int16x8.hpp)
  onnx_digits_reference.rs   reference.hpp's tables: the input grids, the
                             float model's and ONNX Runtime's predictions and
                             the float-activation reference logits

All three models use the importer's arena option, so they run in the arena
tinymind (C++)'s generator plans for them (and need Rust 1.88). The models
and reference.hpp come from the tinymind (C++) checkout at $TINYMIND_DIR
(default ../tinymind); reference.hpp is train.py's output (PyTorch and ONNX
Runtime runs), so it is read, not recomputed. scripts/compare-with-cpp.sh
regenerates all four and checks the committed files are current. Needs numpy
and onnx.
"""

import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import tinymind_import_onnx as ti  # noqa: E402

EXAMPLE = "examples/onnx_digits_int8"
NOTE = ("tinymind (C++)'s {example}/models/{model}: a residual CNN on the UCI optical\n"
        "digits (Conv 3x3 + ReLU -> Conv 3x3 + ReLU added to its input -> MaxPool 2x2\n"
        "-> depthwise Conv 3x3 + ReLU -> pointwise Conv + ReLU -> Linear){what}.")

# file -> (ONNX model, emit options, module name, what the options do)
MODELS = {
    "onnx_digits_model.rs": ("digits_int8.onnx", {}, "onnx_digits", ""),
    "onnx_digits_int4_model.rs": ("digits_qat_int8.onnx", dict(int4_dense=True, int4_conv=True),
                                  "onnx_digits_int4",
                                  ",\nfine-tuned with int4 quantization-aware training, every weight layer on\n"
                                  "packed int4 weights"),
    "onnx_digits_16x8_model.rs": ("digits_int8.onnx", dict(activation_bits=16), "onnx_digits_16x8",
                                  ",\nwith int16 activations and its int8 weights (16x8)"),
}


def array(text: str, name: str) -> list[str]:
    """The initializer values of `constexpr <type> name[N] = { ... };`."""
    m = re.search(r"\b" + name + r"\[(\d+)\]\s*=\s*\{(.*?)\};", text, re.S)
    if m is None:
        raise ValueError(f"reference.hpp: no {name}")
    values = [v.strip() for v in m.group(2).split(",") if v.strip()]
    if len(values) != int(m.group(1)):
        raise ValueError(f"reference.hpp: {name} has {len(values)} values, declares {m.group(1)}")
    return values


def scalar(text: str, name: str) -> int:
    m = re.search(r"\b" + name + r"\s*=\s*(\d+);", text)
    if m is None:
        raise ValueError(f"reference.hpp: no {name}")
    return int(m.group(1))


def rust_array(name: str, ty: str, values: list[str], doc: str, per_line: int) -> list[str]:
    rows = [", ".join(values[i:i + per_line]) for i in range(0, len(values), per_line)]
    return [f"/// {doc}", f"pub static {name}: [{ty}; {len(values)}] = [",
            *[f"    {r}," for r in rows], "];", ""]


def write_reference(reference_hpp: str, path: str) -> None:
    text = open(reference_hpp).read()
    pixel = array(text, "kPixelToInput")
    pixel16 = array(text, "kPixelToInput16")
    float_pred = array(text, "kFloatPrediction")
    ort_pred = array(text, "kOrtPrediction")
    logits = array(text, "kReferenceLogits")
    count = scalar(text, "kTestCount")
    ref_count = scalar(text, "kReferenceLogitCount")
    if len(float_pred) != count or len(ort_pred) != count or len(logits) % ref_count:
        raise ValueError("reference.hpp: inconsistent counts")
    # C++ float literals (`-24.0f`, `1.2e-05f`) are Rust f32 literals without the f.
    floats = [v[:-1] if v.endswith("f") else v for v in logits]
    for v in floats:
        float(v)
    lines = ["//! tinymind (C++)'s examples/onnx_digits_int8/reference.hpp (written by its",
             "//! train.py), as Rust: generated by tools/import_onnx/example_digits.py. Do not",
             "//! edit; regenerate instead.",
             "",
             "// Not every program uses every table.",
             "#![allow(dead_code)]",
             "",
             f"/// Test digits (UCI optdigits.tes).\npub const TEST_COUNT: usize = {count};",
             f"/// Digits with reference logits (the first ones).\npub const REFERENCE_LOGIT_COUNT: usize = {ref_count};",
             ""]
    lines += rust_array("PIXEL_TO_INPUT", "i8", pixel, "Pixel value 0..16 -> the int8 models' input grid.", 17)
    lines += rust_array("PIXEL_TO_INPUT16", "i16", pixel16, "Pixel value 0..16 -> the 16x8 model's input grid.", 17)
    lines += rust_array("FLOAT_PREDICTION", "u8", float_pred,
                        "The class the float PyTorch model predicts for each test digit.", 32)
    lines += rust_array("ORT_PREDICTION", "u8", ort_pred,
                        "The class ONNX Runtime's int8 model predicts for each test digit.", 32)
    lines += rust_array("REFERENCE_LOGITS", "f32", floats,
                        "Logits of the first `REFERENCE_LOGIT_COUNT` digits from the int8-weight model run\n"
                        "/// with float activations: what the int8 and 16x8 models approximate.", 10)
    with open(path, "w") as f:
        f.write("\n".join(lines).rstrip("\n") + "\n")
    rustfmt = shutil.which("rustfmt")
    if rustfmt is None:
        raise SystemExit("example_digits.py: rustfmt not found (the committed files are formatted)")
    subprocess.run([rustfmt, "--edition", "2024", path], check=True)


def main():
    out_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "examples", "common")
    tinymind = os.environ.get("TINYMIND_DIR", os.path.join(os.path.dirname(ROOT), "tinymind"))
    example = os.path.join(tinymind, EXAMPLE)
    for file, (model, opts, name, what) in MODELS.items():
        path = os.path.join(out_dir, file)
        layers = ti.import_onnx_model(os.path.join(example, "models", model), path, name,
                                      NOTE.format(example=EXAMPLE, model=model, what=what),
                                      arena=True, **opts)
        print(f"wrote {path}: {', '.join(layer.op_type for layer in layers)}")
    path = os.path.join(out_dir, "onnx_digits_reference.rs")
    write_reference(os.path.join(example, "reference.hpp"), path)
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
