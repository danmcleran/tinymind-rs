#!/usr/bin/env python3
"""The tree importer's worked example: two classifiers for the UCI Wine data
(13 chemical measurements, 3 cultivars), trained with scikit-learn on 70% of it.

  gbdt    GradientBoostingClassifier, 30 rounds of depth-2 trees, int8 inputs
  forest  RandomForestClassifier, 15 trees of depth 4 voting, int16 inputs

  python3 -I tools/import_trees/example_trees.py --model gbdt \\
      --rust examples/common/imported_trees_gbdt_model.rs
  python3 -I tools/import_trees/example_trees.py --model forest \\
      --rust examples/common/imported_trees_forest_model.rs
  python3 -I tools/import_trees/example_trees.py --data-rust examples/common/imported_trees_data.rs
  python3 -I tools/import_trees/example_trees.py --model gbdt --cpp gbdt.hpp   # tinymind (C++)'s importer
  python3 -I tools/import_trees/example_trees.py --data-cpp trees_data.hpp

--data-* writes the held-out 30% (54 samples) for the example programs.
--cpp runs tinymind (C++)'s own importer (apps/import_trees, from TINYMIND_DIR,
default ../tinymind) on the same model; scripts/compare-with-cpp.sh runs that
header on the tinymind (C++) runtime and byte-compares the output with the Rust
example's. Training is deterministic (fixed random_state), so with the same
scikit-learn version the generated files are reproducible.

The Wine data ships with scikit-learn (UCI Machine Learning Repository,
CC BY 4.0; see NOTICE).
"""

import argparse
import importlib.util
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))


def load(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    sys.dont_write_bytecode = True
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


def split():
    from sklearn.datasets import load_wine
    from sklearn.model_selection import train_test_split
    X, y = load_wine(return_X_y=True)
    return train_test_split(X, y, test_size=0.3, random_state=0, stratify=y)


def trained(model):
    from sklearn.ensemble import GradientBoostingClassifier, RandomForestClassifier
    Xtr, Xte, ytr, yte = split()
    if model == "gbdt":
        m, dtype = GradientBoostingClassifier(n_estimators=30, max_depth=2, random_state=0), "int8"
    else:
        m, dtype = RandomForestClassifier(n_estimators=15, max_depth=4, random_state=0), "int16"
    m.fit(Xtr, ytr)
    return m, dtype, Xtr, Xte, yte


def f32(v) -> str:
    s = str(np.float32(v))
    return s if ("." in s or "e" in s) else s + ".0"


def write_data(path: str, rust: bool) -> None:
    _, Xte, _, yte = split()
    n, F = Xte.shape
    rows = ",\n".join("    [%s]" % ", ".join(f32(v) for v in row) for row in Xte) if rust else \
        ",\n".join("    { %s }" % ", ".join(f32(v) + "f" for v in row) for row in Xte)
    labels = ", ".join(str(int(v)) for v in yte)
    with open(path, "w") as fh:
        if rust:
            fh.write("//! The held-out UCI Wine samples (CC BY 4.0, see NOTICE): generated by\n"
                     "//! tools/import_trees/example_trees.py --data-rust. Do not edit.\n\n"
                     "#![allow(clippy::excessive_precision)]\n\n"
                     "/// Number of samples.\npub const NUM_SAMPLES: usize = %d;\n"
                     "/// The measurements.\npub static TEST_X: [[f32; %d]; NUM_SAMPLES] = [\n%s,\n];\n"
                     "/// The cultivar of each sample (0, 1 or 2).\npub static TEST_Y: [usize; NUM_SAMPLES] = [%s];\n"
                     % (n, F, rows, labels))
        else:
            fh.write("// The held-out UCI Wine samples (CC BY 4.0): generated by\n"
                     "// tinymind-rs tools/import_trees/example_trees.py --data-cpp. Do not edit.\n"
                     "#pragma once\n#include <cstddef>\n\n"
                     "static constexpr std::size_t kNumSamples = %d;\n"
                     "static const float kTestX[kNumSamples][%d] = {\n%s,\n};\n"
                     "static const std::size_t kTestY[kNumSamples] = { %s };\n" % (n, F, rows, labels))
    if rust:
        rustfmt(path)


def rustfmt(path):
    import shutil
    import subprocess
    if shutil.which("rustfmt"):
        subprocess.run(["rustfmt", "--edition", "2024", path], check=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", choices=["gbdt", "forest"], default="gbdt")
    ap.add_argument("--rust", help="write the Rust module (this repo's importer)")
    ap.add_argument("--cpp", help="write a C++ header with tinymind (C++)'s importer")
    ap.add_argument("--data-rust", help="write the test samples as a Rust module")
    ap.add_argument("--data-cpp", help="write the test samples as a C++ header")
    a = ap.parse_args()
    if a.data_rust:
        write_data(a.data_rust, True)
    if a.data_cpp:
        write_data(a.data_cpp, False)
    if not (a.rust or a.cpp):
        return
    m, dtype, Xtr, Xte, yte = trained(a.model)
    if a.rust:
        mod = load(os.path.join(HERE, "tinymind_import_trees.py"), "tinymind_import_trees")
        e = mod.export_trees(m, Xtr, a.rust, a.model, quant=mod.FeatureQuant.from_data(Xtr, dtype))
    if a.cpp:
        tm = os.environ.get("TINYMIND_DIR", os.path.join(ROOT, "..", "tinymind"))
        mod = load(os.path.join(tm, "apps", "import_trees", "tinymind_import_trees.py"), "tinymind_import_trees_cpp")
        e = mod.export_trees(m, Xtr, a.cpp, a.model, quant=mod.FeatureQuant.from_data(Xtr, dtype))
    print(e.report)
    print("held-out accuracy: %.4f (scikit-learn), %.4f (integer model)"
          % (np.mean(m.predict(Xte) == yte), np.mean(e.predict(Xte) == yte)))


if __name__ == "__main__":
    main()
