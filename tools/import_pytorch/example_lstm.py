#!/usr/bin/env python3
"""The importer's LSTM examples:
  lstm     sequences of 12 steps x 3 features -> LSTM, 8 units (int16 cell
           state) -> dense 8 -> 4 -> softmax (a sequence classifier);
  lstm_i8  sequences of 10 steps x 2 features -> LSTM, 5 units (int8 cell
           state) -> dense 5 -> 6 + ReLU -> dense 6 -> 1 -> tanh (a sequence
           regressor).

  python3 -I tools/import_pytorch/example_lstm.py --rust examples/common/imported_lstm_model.rs
  python3 -I tools/import_pytorch/example_lstm.py --model lstm_i8 \\
      --rust examples/common/imported_lstm_i8_model.rs
  python3 -I tools/import_pytorch/example_lstm.py --cpp lstm.hpp

The weights and the calibration set are integer formulas, so they are exact
floats on every platform and the generated file is reproducible. The models
stand in for ones trained in PyTorch; with a real model, use
`tinymind_import.from_torch(nn.Sequential(lstm, head...), sequence_length=T)`.

tinymind (C++)'s importer has no LSTM, so --cpp writes a header of what its
importer would hand the C++ runtime: the float scales, the float LSTM biases,
and the int8 weights and int32 dense biases. scripts/cpp/imported_lstm.cpp
builds every integer parameter from it with tinymind (C++)'s own calibration
functions (buildQLSTMParams, quantizeQLSTMBiases, the LUT builders,
buildRequantizer, buildQSoftmaxFixedPointParams), runs the models on
tinymind (C++)'s QLSTMCell and QDense, and prints what
examples/imported_lstm.rs prints; scripts/compare-with-cpp.sh byte-compares
the two.
"""

import argparse
import importlib.util
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))


def formula(shape: tuple, layer: int, scale: float = 1.0) -> np.ndarray:
    """Exact float weights in [-scale, scale] from an integer formula."""
    n = int(np.prod(shape))
    v = [((k * 7 + (k // 3) * 11 + layer * 5) % 17 - 8) / 8.0 * scale for k in range(n)]
    return np.array(v, dtype=np.float32).reshape(shape)


def bias(n: int, layer: int) -> np.ndarray:
    return np.array([((o * 3 + layer) % 5 - 2) / 8.0 for o in range(n)], dtype=np.float32)


def lstm_bias(hidden: int, layer: int) -> np.ndarray:
    """Gate biases with the forget gate's raised by 1, as LSTMs are usually
    initialised."""
    b = bias(4 * hidden, layer)
    b[hidden:2 * hidden] += 1.0
    return b


def calibration_set(steps: int, features: int) -> list:
    """32 sequences `[step][feature]` in [-1, 1]."""
    return [np.array([[((s * 31 + t * 17 + k * 5 + s * t) % 41) / 20.0 - 1.0
                        for k in range(features)] for t in range(steps)], dtype=np.float32)
            for s in range(32)]


def lstm(mod) -> list:
    dense = mod.dense_ref
    w4, b4 = formula((4, 8), 4), bias(4, 4)
    return [
        mod.LSTM(name="lstm1", weight_ih=formula((32, 3), 1, 0.75), weight_hh=formula((32, 8), 2, 0.5),
                 bias=lstm_bias(8, 3), input_name="input", sequence_length=12, cell_bits=16),
        mod.Dense(name="fc1", weight=w4, bias=b4, input_name="lstm1",
                  forward=lambda x: dense(x, w4, b4)),
        mod.Softmax(name="probs", input_name="fc1"),
    ]


def lstm_i8(mod) -> list:
    dense = mod.dense_ref
    w2, b2 = formula((6, 5), 5), bias(6, 5)
    w3, b3 = formula((1, 6), 6, 0.5), bias(1, 6)
    return [
        mod.LSTM(name="lstm1", weight_ih=formula((20, 2), 7, 1.0), weight_hh=formula((20, 5), 8, 0.5),
                 bias=lstm_bias(5, 9), input_name="input", sequence_length=10, cell_bits=8),
        mod.Dense(name="fc1", weight=w2, bias=b2, input_name="lstm1",
                  forward=lambda x: dense(x, w2, b2)),
        mod.ReLU(name="relu1", input_name="fc1"),
        mod.Dense(name="fc2", weight=w3, bias=b3, input_name="relu1",
                  forward=lambda x: dense(x, w3, b3)),
        mod.Tanh(name="out", input_name="fc2"),
    ]


# name -> (layer builder, steps, features)
MODELS = {
    "lstm": (lstm, 12, 3),
    "lstm_i8": (lstm_i8, 10, 2),
}


def _hex(v: float) -> str:
    """A float32 value as an exact C hexadecimal float literal."""
    return float(np.float32(v)).hex() + "f"


def _ints(a) -> str:
    return "{" + ", ".join(str(int(v)) for v in np.asarray(a).reshape(-1)) + "}"


def write_cpp_header(path: str, namespace: str, mod, layers: list, ranges: dict) -> None:
    """What a C++ importer would emit for the model: float scales and LSTM
    biases, int8 weights (gate-major for the LSTM) and int32 dense biases."""
    out = ["// Generated by tools/import_pytorch/example_lstm.py --cpp. Do not edit.",
           "#pragma once", "#include <cstdint>", "", f"namespace {namespace}", "{"]
    for name, (scale, zp) in ranges.items():
        out.append(f"    static const float k{name}_Scale = {_hex(scale)};")
        out.append(f"    static const int32_t k{name}_ZeroPoint = {int(zp)};")
    for layer in layers:
        n = layer.name
        if isinstance(layer, mod.LSTM):
            out.append(f"    static const float k{n}_CellScale = {_hex(layer.cell_scale)};")
            out.append(f"    static const float k{n}_LutInputScale = {_hex(mod.LSTM_LUT_INPUT_SCALE)};")
            out.append(f"    static const float k{n}_InputWeightScale[4] = "
                       "{" + ", ".join(_hex(v) for v in layer.input_weight_scales) + "};")
            out.append(f"    static const float k{n}_RecurrentWeightScale[4] = "
                       "{" + ", ".join(_hex(v) for v in layer.recurrent_weight_scales) + "};")
            out.append(f"    static const int8_t k{n}_InputWeights[] = {_ints(layer.q_weight_ih)};")
            out.append(f"    static const int8_t k{n}_RecurrentWeights[] = {_ints(layer.q_weight_hh)};")
            out.append(f"    static const float k{n}_Bias[] = "
                       "{" + ", ".join(_hex(v) for v in layer.bias) + "};")
        elif isinstance(layer, mod.Dense):
            out.append(f"    static const float k{n}_WeightScale = {_hex(layer.weight_scale)};")
            out.append(f"    static const int8_t k{n}_Weights[] = {_ints(layer.q_weight)};")
            out.append(f"    static const int32_t k{n}_Biases[] = {_ints(layer.q_bias)};")
    out.append("}")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")


def load(path: str, name: str):
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    sys.dont_write_bytecode = True
    sys.modules[name] = mod  # dataclasses look their module up while it executes
    spec.loader.exec_module(mod)
    return mod


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", choices=sorted(MODELS), default="lstm")
    ap.add_argument("--rust", help="write the Rust module")
    ap.add_argument("--cpp", help="write the C++ check header")
    args = ap.parse_args()
    build, steps, features = MODELS[args.model]
    mod = load(os.path.join(HERE, "tinymind_import.py"), "tinymind_import_rs")
    model_name = f"example_{args.model}"
    data = calibration_set(steps, features)
    if args.rust:
        ranges = mod.import_pytorch_model(build(mod), "input", mod.MinMaxObserver(), data,
                                          args.rust, model_name)
        print("wrote", args.rust, {k: (round(s, 6), z) for k, (s, z) in ranges.items()})
    if args.cpp:
        layers = mod.fuse_layers(build(mod))
        ranges = mod.calibrate(layers, "input", mod.MinMaxObserver(), data)
        mod.quantize_weights(layers, ranges)
        write_cpp_header(args.cpp, model_name, mod, layers, ranges)
        print("wrote", args.cpp)


if __name__ == "__main__":
    main()
