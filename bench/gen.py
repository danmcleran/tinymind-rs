#!/usr/bin/env python3
"""Generate the int8 models for the board benchmark from tinymind's own
benchmark (benchmarks/framework_comparison_f411/gen/out/), so the Rust and C++
runs use the same int8 weights, requantizers and test inputs:

  bench/src/gen/mlp.rs  the digits MLP (not committed: it embeds test samples
                        from the UCI digits data, CC BY 4.0, which tinymind's
                        header carries the credit for)
  bench/src/gen/kws.rs  the KWS-shaped CNN (random weights and inputs)

Usage: python3 -I bench/gen.py <n_samples>   (360 for the F411, 32 for the L031,
as tinymind uses). TINYMIND_DIR overrides ../tinymind.
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
TM = os.environ.get("TINYMIND_DIR", os.path.join(ROOT, "..", "tinymind"))
BENCH = os.path.join(TM, "benchmarks", "framework_comparison_f411")
MODEL = os.path.join(BENCH, "gen", "out", "mlp_tinymind.hpp")
DATA = os.path.join(BENCH, "gen", "out", "mlp_data.h")
BACKEND = os.path.join(BENCH, "fw", "backend.hpp")
OUT = os.path.join(HERE, "src", "gen", "mlp.rs")
KWS_MODEL = os.path.join(BENCH, "gen", "out", "kws_tinymind.hpp")
KWS_DATA = os.path.join(BENCH, "gen", "out", "kws_data.h")
KWS_OUT = os.path.join(HERE, "src", "gen", "kws.rs")

LAYERS = [("L0", 64, 32), ("L1", 32, 16), ("L2", 16, 10)]


def ints(text):
    return [int(v) for v in re.findall(r"-?\d+", text)]


def array(src, decl):
    m = re.search(re.escape(decl) + r"\s*=\s*\{(.*?)\};", src, re.S)
    if not m:
        sys.exit("not found: " + decl)
    return m.group(1)


def rq_list(vals):
    return ", ".join(
        "Requantizer { multiplier: %d, shift: %d, zero_point: %d, qmin: %d, qmax: %d }" % tuple(vals[i:i + 5])
        for i in range(0, len(vals), 5))


def nested(vals, dims):
    """A Rust nested-array literal of vals (memory order) with shape dims."""
    if len(dims) == 1:
        assert len(vals) == dims[0]
        return "[" + ", ".join(map(str, vals)) + "]"
    step = len(vals) // dims[0]
    return "[" + ", ".join(nested(vals[i * step:(i + 1) * step], dims[1:]) for i in range(dims[0])) + "]"


def gen_kws(backend):
    """The KWS-shaped CNN: conv 3x3x8 (per channel), max pool 2x2, depthwise
    3x3, pointwise 8->16 (per channel), global average pool, pointwise 16->10."""
    model = open(KWS_MODEL).read()
    data = open(KWS_DATA).read()
    # The layer shapes this file assumes: fail loudly if tinymind changes them.
    for decl in [
        "QConv2DPerChannel<int8_t, int8_t, int32_t, int8_t, 20, 20, 1, 3, 3, 1, 1, 8>",
        "QMaxPool2D<int8_t, 18, 18, 8, 2, 2, 2, 2>",
        "QDepthwiseConv2D<int8_t, int8_t, int32_t, int8_t, 9, 9, 8, 3, 3, 1, 1>",
        "QPointwiseConv2DPerChannel<int8_t, int8_t, int32_t, int8_t, 7, 7, 8, 16>",
        "QGlobalAvgPool2D<int8_t, int32_t, 7, 7, 16>",
        "QPointwiseConv2DPerChannel<int8_t, int8_t, int32_t, int8_t, 1, 1, 16, 10>",
    ]:
        assert decl in model, decl
    layers = [
        # name, weights decl, count, Rust shape, biases, requantizers, layer init
        ("C1", "alignas(4) const int8_t Wc1[72]", [8, 3, 3, 1], "Bc1[8]", "Rc1[8]", "C1Type C1 = {Wc1, Bc1, (-?\\d+), Rc1}"),
        ("DW", "alignas(4) const int8_t Wdw[72]", [8, 3, 3], "Bdw[8]", "Rdw[8]", "DwType DW = {Wdw, Bdw, (-?\\d+), Rdw}"),
        ("PW", "alignas(4) const int8_t Wpw[128]", [16, 8], "Bpw[16]", "Rpw[16]", "PwType PW = {Wpw, Bpw, (-?\\d+), Rpw}"),
        ("D", "alignas(4) const int8_t W_D[160]", [10, 16], "B_D[10]", "R_D[10]", "DType D = {W_D, B_D, (-?\\d+), R_D}"),
    ]
    out = [
        "// Generated by bench/gen.py from tinymind's benchmarks/framework_comparison_f411",
        "// (gen/out/kws_tinymind.hpp, gen/out/kws_data.h, fw/backend.hpp). Do not edit.",
        "// Random weights and inputs (gen/make_models.py): no dataset.",
        "use tinymind::int8::Requantizer;",
        "",
    ]
    for name, wdecl, dims, bdecl, rdecl, init in layers:
        n = 1
        for d in dims:
            n *= d
        w = ints(array(model, wdecl))
        b = ints(array(model, "const int32_t " + bdecl))
        r = ints(array(model, "const Rq " + rdecl))
        nf = dims[0]
        assert len(w) == n and len(b) == nf and len(r) == 5 * nf, name
        zp = re.search(init.replace("{", "\\{").replace("}", "\\}"), model)
        assert zp, name
        ty = "i8"
        for d in reversed(dims):
            ty = "[%s; %d]" % (ty, d)
        out.append("pub static W_%s: %s = %s;" % (name, ty, nested(w, dims)))
        out.append("pub static B_%s: [i32; %d] = [%s];" % (name, nf, ", ".join(map(str, b))))
        out.append("pub static R_%s: [Requantizer; %d] = [%s];" % (name, nf, rq_list(r)))
        out.append("pub const ZP_%s: i8 = %s;" % (name, zp.group(1)))
    gap = re.search(r"const GapType GAP = \{(-?\d+), (-?\d+)\};", model)
    assert gap
    out.append("pub const GAP_QMIN: i8 = %s;" % gap.group(1))
    out.append("pub const GAP_QMAX: i8 = %s;" % gap.group(2))
    n_test = int(re.search(r"#define KWS_N_TEST (\d+)", data).group(1))
    x = ints(array(data, "alignas(4) const int8_t kws_test_x_i8[%d]" % (n_test * 400)))
    out.append("pub const N_TEST: usize = %d;" % n_test)
    out.append("pub static X: [[[[i8; 1]; 20]; 20]; N_TEST] = %s;" % nested(x, [n_test, 20, 20, 1]))
    h = re.search(r"#define TM_KWS_HASH (0x[0-9A-Fa-f]+)u", backend)
    assert h
    out.append("/// tinymind's expected output hash (TM_KWS_HASH in fw/backend.hpp).")
    out.append("pub const EXPECT_HASH: u32 = %s;" % h.group(1))
    with open(KWS_OUT, "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote %s (%d samples, expect hash %s)" % (os.path.relpath(KWS_OUT, ROOT), n_test, h.group(1)))


def main():
    n = int(sys.argv[1])
    model = open(MODEL).read()
    data = open(DATA).read()
    backend = open(BACKEND).read()
    expect = {360: "TM_MLP_HASH", 32: "TM_MLP_HASH_32"}[n]
    h = re.search(r"#define " + expect + r" (0x[0-9A-Fa-f]+)u", backend)
    assert h, expect

    out = [
        "// Generated by bench/gen.py from tinymind's benchmarks/framework_comparison_f411",
        "// (gen/out/mlp_tinymind.hpp, gen/out/mlp_data.h, fw/backend.hpp). Do not edit.",
        "// Test samples: UCI Optical Recognition of Handwritten Digits (E. Alpaydin and",
        "// C. Kaynak, 1998, https://doi.org/10.24432/C50P49), CC BY 4.0.",
        "use tinymind::int8::Requantizer;",
        "",
    ]
    for name, n_in, n_out in LAYERS:
        w = ints(array(model, "alignas(4) const int8_t W_%s[%d]" % (name, n_in * n_out)))
        b = ints(array(model, "const int32_t B_%s[%d]" % (name, n_out)))
        r = ints(array(model, "const Rq R_%s[%d]" % (name, n_out)))
        assert len(w) == n_in * n_out and len(b) == n_out and len(r) == 5 * n_out, name
        zp = re.search(r"const %sType %s = \{W_%s, B_%s, (-?\d+), R_%s\};" % (name, name, name, name, name), model)
        assert zp, name
        rows = ["[" + ", ".join(map(str, w[o * n_in:(o + 1) * n_in])) + "]" for o in range(n_out)]
        out.append("pub static W_%s: [[i8; %d]; %d] = [%s];" % (name, n_in, n_out, ", ".join(rows)))
        out.append("pub static B_%s: [i32; %d] = [%s];" % (name, n_out, ", ".join(map(str, b))))
        rqs = ["Requantizer { multiplier: %d, shift: %d, zero_point: %d, qmin: %d, qmax: %d }" % tuple(r[5 * i:5 * i + 5]) for i in range(n_out)]
        out.append("pub static R_%s: [Requantizer; %d] = [%s];" % (name, n_out, ", ".join(rqs)))
        out.append("pub const ZP_%s: i8 = %s;" % (name, zp.group(1)))
    x = ints(array(data, "alignas(4) const int8_t mlp_test_x_i8[23040]"))
    y = ints(array(data, "const uint8_t mlp_test_y[360]"))
    assert len(x) == 360 * 64 and len(y) == 360
    rows = ["[" + ", ".join(map(str, x[s * 64:(s + 1) * 64])) + "]" for s in range(n)]
    out.append("pub const N_TEST: usize = %d;" % n)
    out.append("pub static X: [[i8; 64]; N_TEST] = [%s];" % ", ".join(rows))
    out.append("pub static Y: [u8; N_TEST] = [%s];" % ", ".join(map(str, y[:n])))
    out.append("/// tinymind's expected output hash (%s in fw/backend.hpp).", )
    out[-1] = out[-1] % expect
    out.append("pub const EXPECT_HASH: u32 = %s;" % h.group(1))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote %s (%d samples, expect hash %s)" % (os.path.relpath(OUT, ROOT), n, h.group(1)))
    gen_kws(backend)


if __name__ == "__main__":
    main()
