#!/usr/bin/env bash
# Mechanical checks that the hand-written docs keep up with the code. Prose
# cannot be checked this way; see "Keeping the docs current" in CLAUDE.md for
# the rest. Run from anywhere; CI runs it in the `rust` job.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
status=0
fail() { echo "check-docs: $*" >&2; status=1; }

# 1. Every example is in the README's and the site's quick start.
for f in examples/*.rs; do
  name="$(basename "$f" .rs)"
  for doc in README.md docs/index.md; do
    grep -q -- "--example $name\b" "$doc" || fail "$doc has no 'cargo run ... --example $name' line"
  done
done

# 2. Every site link resolves: {{ site.baseurl }}/x must be docs/x.md, a
#    directory index, or a file under docs/ (api/ is generated by pages.yml).
while IFS= read -r link; do
  target="${link#/}"
  target="${target%%#*}"
  [ -z "$target" ] && continue
  case "$target" in api/*) continue ;; esac
  if [ ! -e "docs/$target" ] && [ ! -e "docs/${target%/}.md" ]; then
    fail "site link {{ site.baseurl }}/$target has no page or file in docs/"
  fi
done < <(grep -ohE '\{\{ site\.baseurl \}\}(/[^) "]*)' docs/*.md | sed -E 's/\{\{ site\.baseurl \}\}//' | sort -u)

# 3. Every page in the site nav has a distinct nav_order.
dups="$(grep -h '^nav_order:' docs/*.md | sort | uniq -d)"
[ -z "$dups" ] || fail "duplicate nav_order in docs/: $dups"

# 4. The CHANGELOG has an [Unreleased] section and an entry for the crate's
#    current version.
version="$(sed -n 's/^version = "\(.*\)"$/\1/p' Cargo.toml | head -1)"
grep -q '^## \[Unreleased\]' CHANGELOG.md || fail "CHANGELOG.md has no [Unreleased] section"
grep -q "^## \[$version\]" CHANGELOG.md || fail "CHANGELOG.md has no entry for $version (Cargo.toml)"

# 5. Every example data file is attributed in NOTICE and data/README.md.
for f in data/*; do
  base="$(basename "$f")"
  [ "$base" = README.md ] && continue
  grep -q "$base" NOTICE || fail "NOTICE does not mention data/$base"
  grep -q "$base" data/README.md || fail "data/README.md does not mention $base"
done

[ "$status" -eq 0 ] && echo "check-docs: ok"
exit "$status"
